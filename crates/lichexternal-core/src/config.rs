//! Configuration structures, validation, and cross-platform path resolution.

use alloc::collections::BTreeMap;
use alloc::string::String;
use alloc::vec::Vec;
use serde::{Deserialize, Serialize};

use crate::models::UciVariant;

/// Configuration errors.
#[derive(Debug, thiserror::Error)]
pub enum ConfigError {
    /// Failed to parse TOML configuration.
    #[cfg(feature = "std")]
    #[error("TOML parse error: {0}")]
    Toml(#[from] toml::de::Error),

    /// File I/O error when reading configuration.
    #[cfg(feature = "std")]
    #[error("I/O error reading config from '{0}': {source}", path.display())]
    Io {
        path: std::path::PathBuf,
        source: std::io::Error,
    },

    /// Validation error in configuration settings.
    #[error("Configuration validation error: {0}")]
    Validation(String),
}

/// Backend transport type for communicating with a chess engine.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum BackendType {
    /// Local subprocess communicating via standard input/output (`stdin`/`stdout`).
    Stdio,
    /// Persistent background daemon communicating via Unix Domain Socket or Windows Named Pipe.
    Socket,
}

/// Profile configuration for an individual chess engine.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct EngineConfig {
    /// Registered engine ID on Lichess.
    pub id: String,
    /// Provider secret generated by Lichess for broker work polling.
    pub provider_secret: String,
    /// Human-readable display name.
    pub name: String,
    /// Transport backend: `stdio` or `socket`.
    #[serde(rename = "type")]
    pub backend_type: BackendType,
    /// Path or executable name (for `stdio` engines).
    #[serde(default)]
    pub command: Option<String>,
    /// Command-line arguments (for `stdio` engines).
    #[serde(default)]
    pub args: Vec<String>,
    /// Socket path or Windows Named Pipe address (for `socket` engines).
    #[serde(default)]
    pub socket: Option<String>,
    /// Maximum calculation threads allowed.
    #[serde(default = "default_threads")]
    pub max_threads: u32,
    /// Maximum hash / transposition table memory in MiB.
    #[serde(default = "default_hash")]
    pub max_hash: u32,
    /// Supported chess variants.
    #[serde(default = "default_variants")]
    pub variants: Vec<UciVariant>,
    /// Static UCI options initialized on startup.
    #[serde(default)]
    pub uci_options: BTreeMap<String, String>,
}

const fn default_threads() -> u32 {
    1
}

const fn default_hash() -> u32 {
    64
}

fn default_variants() -> Vec<UciVariant> {
    alloc::vec![UciVariant::Chess]
}

impl EngineConfig {
    /// Validates the engine configuration fields.
    pub fn validate(&self) -> Result<(), ConfigError> {
        if self.id.trim().is_empty() {
            return Err(ConfigError::Validation(String::from("Engine 'id' cannot be empty")));
        }
        if self.provider_secret.trim().is_empty() {
            return Err(ConfigError::Validation(alloc::format!(
                "Engine '{}' must have a non-empty provider_secret",
                self.id
            )));
        }
        if self.max_threads == 0 {
            return Err(ConfigError::Validation(alloc::format!(
                "Engine '{}' max_threads must be at least 1",
                self.id
            )));
        }
        if self.max_hash == 0 {
            return Err(ConfigError::Validation(alloc::format!(
                "Engine '{}' max_hash must be at least 1 MiB",
                self.id
            )));
        }

        match self.backend_type {
            BackendType::Stdio => {
                if self.command.as_deref().unwrap_or("").trim().is_empty() {
                    return Err(ConfigError::Validation(alloc::format!(
                        "Engine '{}' has type 'stdio' but no 'command' binary specified",
                        self.id
                    )));
                }
            }
            BackendType::Socket => {
                if self.socket.as_deref().unwrap_or("").trim().is_empty() {
                    return Err(ConfigError::Validation(alloc::format!(
                        "Engine '{}' has type 'socket' but no 'socket' path specified",
                        self.id
                    )));
                }
            }
        }

        Ok(())
    }
}

/// Global configuration for the Lichexternal service.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Config {
    /// Path to local IPC socket for daemon control and status.
    #[serde(default)]
    pub socket_path: Option<String>,
    /// Log verbosity level (`trace`, `debug`, `info`, `warn`, `error`).
    #[serde(default = "default_log_level")]
    pub log_level: String,
    /// Optional Lichess User API Personal Access Token for remote engine CRUD.
    #[serde(default)]
    pub lichess_token: Option<String>,
    /// Base URL for Lichess REST API.
    #[serde(default = "default_lichess_base_url")]
    pub lichess_base_url: String,
    /// Base URL for Lichess Engine Work Broker.
    #[serde(default = "default_broker_base_url")]
    pub broker_base_url: String,
    /// Configured chess engine profiles.
    #[serde(default)]
    pub engines: Vec<EngineConfig>,
}

fn default_log_level() -> String {
    String::from("info")
}

fn default_lichess_base_url() -> String {
    String::from("https://lichess.org")
}

fn default_broker_base_url() -> String {
    String::from("https://engine.lichess.ovh")
}

impl Default for Config {
    fn default() -> Self {
        Self {
            socket_path: None,
            log_level: default_log_level(),
            lichess_token: None,
            lichess_base_url: default_lichess_base_url(),
            broker_base_url: default_broker_base_url(),
            engines: Vec::new(),
        }
    }
}

impl Config {
    /// Validates all configuration sections and engine profiles.
    pub fn validate(&self) -> Result<(), ConfigError> {
        for engine in &self.engines {
            engine.validate()?;
        }
        Ok(())
    }

    /// Parses and validates a configuration from a TOML string.
    #[cfg(feature = "std")]
    pub fn from_toml_str(content: &str) -> Result<Self, ConfigError> {
        let config: Self = toml::from_str(content)?;
        config.validate()?;
        Ok(config)
    }

    /// Reads and validates configuration from a file path.
    #[cfg(feature = "std")]
    pub fn load_from_path(path: &std::path::Path) -> Result<Self, ConfigError> {
        let content = std::fs::read_to_string(path).map_err(|e| ConfigError::Io {
            path: path.to_path_buf(),
            source: e,
        })?;
        Self::from_toml_str(&content)
    }

    /// Resolves the default standard configuration file path for the current OS.
    #[cfg(feature = "std")]
    #[must_use]
    pub fn default_config_path() -> Option<std::path::PathBuf> {
        use etcetera::base_strategy::{choose_base_strategy, BaseStrategy};
        let strategy = choose_base_strategy().ok()?;
        Some(strategy.config_dir().join("lichexternal").join("config.toml"))
    }

    /// Resolves the default standard daemon control IPC socket path for the current OS.
    #[cfg(feature = "std")]
    #[must_use]
    pub fn default_socket_path() -> std::path::PathBuf {
        #[cfg(windows)]
        {
            std::path::PathBuf::from(r"\\.\pipe\lichexternald")
        }
        #[cfg(not(windows))]
        {
            use etcetera::base_strategy::{choose_base_strategy, BaseStrategy};
            if let Ok(strategy) = choose_base_strategy() {
                if let Some(runtime_dir) = strategy.runtime_dir() {
                    return runtime_dir.join("lichexternal").join("lichexternald.sock");
                }
            }
            std::path::PathBuf::from("/tmp/lichexternald.sock")
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_parse_valid_toml_config() {
        let toml_str = r#"
log_level = "debug"
lichess_base_url = "https://lichess.org"
broker_base_url = "https://engine.lichess.ovh"

[[engines]]
id = "stockfish-local"
provider_secret = "secret-123"
name = "Stockfish 19"
type = "stdio"
command = "/usr/bin/stockfish"
args = ["--eval"]
max_threads = 16
max_hash = 4096
variants = ["chess", "atomic"]

[engines.uci_options]
SyzygyPath = "/tablebases"

[[engines]]
id = "chexpectimax-socket"
provider_secret = "secret-456"
name = "Chexpectimax"
type = "socket"
socket = "/run/user/1000/chexpectimax.sock"
max_threads = 8
max_hash = 2048
"#;

        let config = Config::from_toml_str(toml_str).unwrap();
        assert_eq!(config.log_level, "debug");
        assert_eq!(config.engines.len(), 2);

        let sf = &config.engines[0];
        assert_eq!(sf.id, "stockfish-local");
        assert_eq!(sf.backend_type, BackendType::Stdio);
        assert_eq!(sf.command.as_deref(), Some("/usr/bin/stockfish"));
        assert_eq!(sf.args, vec!["--eval"]);
        assert_eq!(sf.max_threads, 16);
        assert_eq!(sf.max_hash, 4096);
        assert_eq!(sf.variants, vec![UciVariant::Chess, UciVariant::Atomic]);
        assert_eq!(sf.uci_options.get("SyzygyPath").map(|s| s.as_str()), Some("/tablebases"));

        let ch = &config.engines[1];
        assert_eq!(ch.id, "chexpectimax-socket");
        assert_eq!(ch.backend_type, BackendType::Socket);
        assert_eq!(ch.socket.as_deref(), Some("/run/user/1000/chexpectimax.sock"));
    }

    #[test]
    fn test_validate_missing_command() {
        let toml_str = r#"
[[engines]]
id = "bad-engine"
provider_secret = "sec"
name = "Bad"
type = "stdio"
"#;
        let err = Config::from_toml_str(toml_str).unwrap_err();
        match err {
            ConfigError::Validation(msg) => {
                assert!(msg.contains("no 'command' binary specified"));
            }
            _ => panic!("Expected ConfigError::Validation"),
        }
    }
}
